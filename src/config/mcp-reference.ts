import { LATEST_PROTOCOL_VERSION, SUPPORTED_PROTOCOL_VERSIONS, type Tool } from "@modelcontextprotocol/server";

import type { AnyCapability } from "@/core/capability";
import {
  type ExposedEntry,
  exposedCapabilities,
  IDEMPOTENCY_ARGUMENT,
  IDEMPOTENCY_META_KEY,
  type McpManifest,
  RISK_TIER_META_KEY,
  toolListVersion,
  toolNameOf,
  toolOf,
  type UiOnlyEntry,
} from "@/core/mcp/server";

import { demoActor } from "./actor";
import { CATALOG } from "./catalog";
import { DEMO_MCP_TOKENS } from "./mcp-env";
import { MCP_PATH } from "./mcp-http.server";
import { MCP_MANIFEST } from "./mcp-manifest";
import { VERTICALS, type VerticalId } from "./vertical";

/**
 * `docs/mcp/reference.md` (spec 004 AC10), rendered from the projection the server itself uses: the manifest picks the
 * tools, `toolOf` gives each its name, title, description, schema, annotations and tier, and `toolListVersion` the
 * `serverInfo.version`. Nothing here lists a tool by hand. The output is deterministic: tools by name, presets and
 * UI-only entries by id, no timestamps. `npm run mcp:reference` writes it; a test fails when the file is stale.
 */

/** The revision of the 2026 era the SDK's handlers serve; the SDK exports only the 2025 era's list. */
/** The manifest as the projection reads it: every entry exposed or UI-only. */
const MANIFEST: McpManifest = MCP_MANIFEST;

const MODERN_PROTOCOL_REVISION = "2026-07-28";

/** The file the reference is written to, relative to the repository root. */
export const MCP_REFERENCE_PATH = "docs/mcp/reference.md";

interface ProjectedTool {
  readonly capability: AnyCapability;
  readonly entry: ExposedEntry;
  readonly tool: Tool;
}

const byText = (a: string, b: string): number => Number(a > b) - Number(a < b);

/** Every tool the deployment exposes, projected as `toolListVersion` hashes them, in name order. */
const projectedTools = (): readonly ProjectedTool[] => {
  const exposed = exposedCapabilities(CATALOG, MANIFEST);
  const toolIds = new Set(exposed.map((capability) => capability.id));
  return exposed
    .map((capability) => {
      const entry = MANIFEST[capability.id] as ExposedEntry;
      return { capability, entry, tool: toolOf(capability, entry, toolIds) };
    })
    .sort((a, b) => byText(a.tool.name, b.tool.name));
};

const presetIds = (): readonly VerticalId[] => (Object.keys(VERTICALS) as VerticalId[]).sort(byText);

const code = (text: string): string => `\`${text}\``;

/** A table cell: a pipe or a line break would end the cell early. */
const cell = (text: string): string => text.replaceAll("|", "\\|").replaceAll("\n", " ");

const table = (header: readonly string[], rows: readonly (readonly string[])[]): string[] => [
  `| ${header.join(" | ")} |`,
  `| ${header.map(() => "---").join(" | ")} |`,
  ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
];

const effectOf = (tool: Tool): string => (tool.annotations?.readOnlyHint === true ? "read" : "write");

const idempotencyOf = (capability: AnyCapability): string => capability.idempotency ?? "n/a (read)";

const tierOf = (tool: Tool): string => String(tool._meta?.[RISK_TIER_META_KEY]);

const anchorOf = (tool: Tool): string => `[${code(tool.name)}](#${tool.name})`;

const headerSection = (): string[] => {
  const demoTokens = DEMO_MCP_TOKENS.split(",").map((entry) => code(entry.split(":")[0] ?? entry));
  return [
    "# admin-OS MCP reference",
    "",
    `> Generated by ${code("npm run mcp:reference")} from the MCP manifest (${code("src/config/mcp-manifest.ts")}) and the tool projection (${code("src/core/mcp/project-catalog.ts")}). Do not edit it by hand: ${code("npm test")} fails while it is stale.`,
    "",
    "admin-OS serves its capability catalogue as MCP tools, through the same client as the web app: permissions, approval, validation and error codes are the screens' own (ADR 0009). Each tool is one capability the manifest exposes; a UI-only capability is never a tool.",
    "",
    "## The server",
    "",
    `- **Protocol.** Revision ${code(MODERN_PROTOCOL_REVISION)}, and the 2025 era (${SUPPORTED_PROTOCOL_VERSIONS.map(code).join(", ")}; latest ${code(LATEST_PROTOCOL_VERSION)}) through the SDK's stateless fallback, on both transports.`,
    `- **Transports.** Streamable HTTP at ${code(MCP_PATH)} (GET, POST and DELETE), and stdio with ${code("npm run --silent mcp:stdio")}. The preset is the deployment's ${code("VERTICAL")}.`,
    `- **Auth over HTTP.** A bearer token is required and resolves the role; no token never means a role. ${code("MCP_TOKENS")} maps tokens to roles (${code("<token>:<role>,...")}). While it is unset on the mock adapter, the public demo tokens ${demoTokens.join(", ")} apply, each with its own demo session, and the server is **read-only**: anyone holds those tokens. ${code("MCP_READ_ONLY=true")} or ${code("false")} overrides either default.`,
    `- **Auth over stdio.** One actor per process: ${code("MCP_ROLE")} (default ${code("staff")}) on its own demo session; it writes unless ${code("MCP_READ_ONLY=true")}.`,
    `- **Read-only mode.** Only the tools marked ${code("read")} below are listed and run; a write answers ${code("access.forbidden")}.`,
    `- **Visibility.** An actor is offered only the tools its role's permissions allow, sorted by name. Descriptions here name every exposed tool; a server names only the tools its actor is offered.`,
    `- **Idempotency.** A tool whose mode is ${code("key")} requires the ${code(IDEMPOTENCY_ARGUMENT)} argument: a new UUID per operation, the same one to retry it. A host may also send ${code(`_meta["${IDEMPOTENCY_META_KEY}"]`)}. A ${code("target-state")} tool takes no key: repeating it reaches the same state.`,
    `- **Tier.** Each tool's ${code(`_meta["${RISK_TIER_META_KEY}"]`)}: 0 non-personal read, 1 personal read or self-scoped write, 2 business write, 3 irreversible, money or legal.`,
    "",
  ];
};

const versionsSection = (): string[] => [
  "## `serverInfo.version`",
  "",
  "A hash of the manifest, the read-only switch and every exposed tool: it changes whenever a tool does.",
  "",
  ...table(
    ["Preset", "Read-write", "Read-only"],
    presetIds().map((id) => [
      id,
      code(toolListVersion(CATALOG, MANIFEST, false)),
      code(toolListVersion(CATALOG, MANIFEST, true)),
    ]),
  ),
  "",
];

/** The tools some role of the preset may call, each with the roles that hold its permission. */
const presetSection = (id: VerticalId, tools: readonly ProjectedTool[]): string[] => {
  const vertical = VERTICALS[id];
  const actors = vertical.roles.map((role) => demoActor(role.id, vertical));
  const rows = tools
    .map(({ capability, tool }) => {
      const roles = actors.filter((actor) => actor.permissions.includes(capability.permission));
      return { capability, tool, roles: roles.map((actor) => actor.roleId) };
    })
    .filter(({ roles }) => roles.length > 0)
    .map(({ capability, tool, roles }) => [
      anchorOf(tool),
      tool.title ?? "",
      effectOf(tool),
      tierOf(tool),
      idempotencyOf(capability),
      String(tool.annotations?.destructiveHint),
      code(capability.permission),
      roles.join(", "),
    ]);
  return [
    `### ${id}`,
    "",
    ...table(["Tool", "Title", "Effect", "Tier", "Idempotency", "destructiveHint", "Permission", "Roles"], rows),
    "",
  ];
};

const presetsSection = (tools: readonly ProjectedTool[]): string[] => [
  "## Tools by preset",
  "",
  ...presetIds().flatMap((id) => presetSection(id, tools)),
];

const idHintsOf = (entry: ExposedEntry): string[] =>
  Object.entries(entry.ids ?? {})
    .sort(([a], [b]) => byText(a, b))
    .map(([field, ids]) => `  - ${code(field)}: ${ids.map((id) => code(toolNameOf(id))).join(", ")}`);

const toolSection = ({ capability, entry, tool }: ProjectedTool): string[] => {
  const { $schema: _dialect, ...inputSchema } = tool.inputSchema;
  const hints = idHintsOf(entry);
  const annotations = Object.entries(tool.annotations ?? {})
    .map(([name, value]) => `${code(name)} ${String(value)}`)
    .join(", ");
  return [
    `### ${code(tool.name)}`,
    "",
    `**${tool.title ?? ""}.** ${tool.description ?? ""}`,
    "",
    `- Capability: ${code(capability.id)}, permission ${code(capability.permission)}, tier ${tierOf(tool)}, idempotency ${idempotencyOf(capability)}.`,
    `- Annotations: ${annotations}.`,
    ...(hints.length === 0 ? [] : ["- Id hints (field: tools that list valid values):", ...hints]),
    "",
    "```json",
    JSON.stringify(inputSchema, null, 2),
    "```",
    "",
  ];
};

const toolsSection = (tools: readonly ProjectedTool[]): string[] => [
  "## Tools",
  "",
  "Each tool's input schema is JSON Schema 2020-12, as `tools/list` sends it (without `$schema`).",
  "",
  ...tools.flatMap(toolSection),
];

const uiOnlySection = (): string[] => {
  const uiOnly = Object.entries(MANIFEST)
    .filter((pair): pair is [string, UiOnlyEntry] => "uiOnly" in pair[1])
    .sort(([a], [b]) => byText(a, b))
    .map(([id, entry]) => [code(id), entry.uiOnly]);
  return [
    "## UI-only capabilities",
    "",
    "Capabilities only the web app calls; they are never tools.",
    "",
    ...table(["Capability", "Reason"], uiOnly),
  ];
};

/** The whole reference, ending with one newline. */
export const renderMcpReference = (): string => {
  const tools = projectedTools();
  return `${[...headerSection(), ...versionsSection(), ...presetsSection(tools), ...toolsSection(tools), ...uiOnlySection()].join("\n")}\n`;
};
